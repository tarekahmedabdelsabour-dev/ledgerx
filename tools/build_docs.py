"""Builds ledgerx/public/docs/content_{ar,en}.js from tools/docs_src/{ar,en}/<page>.md."""
import json, os, re, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "..", "ledgerx", "public", "docs")
BAD = re.compile(r"erpnext|frappe", re.I)

for lang in ("ar", "en"):
	d = os.path.join(ROOT, "docs_src", lang)
	body = {}
	if os.path.isdir(d):
		for f in sorted(os.listdir(d)):
			if f.endswith(".md"):
				t = open(os.path.join(d, f), encoding="utf-8").read().strip()
				if BAD.search(t):
					sys.exit(f"forbidden brand word in {lang}/{f}")
				body[f[:-3]] = t
	js = "/* generated by tools/build_docs.py - edit tools/docs_src instead */\nwindow.LXD.body.%s=%s;\n" % (lang, json.dumps(body, ensure_ascii=False))
	open(os.path.join(OUT, f"content_{lang}.js"), "w", encoding="utf-8").write(js)
	print(lang, len(body), "pages")
